def _spearman(a, b):
    a = pd.Series(list(a)).rank().to_numpy(dtype=float)
    b = pd.Series(list(b)).rank().to_numpy(dtype=float)
    a = a - a.mean()
    b = b - b.mean()
    den = ((a * a).sum() * (b * b).sum()) ** 0.5
