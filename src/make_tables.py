# ---------------------------------------------------------------- 서식 도우미
def f4(x):
    return "%.4f" % float(x)


def f3(x):
    return "%.3f" % float(x)


def f2(x):
    return "%.2f" % float(x)


def p1(x):
    return "%.1f\\%%" % float(x)


def p0(x):
    return "%.0f\\%%" % float(x)


def sg(x):
    return "%+.4f" % float(x)


def ci3(lo, hi):
    """저널 관행대로 신뢰구간은 세 자리로 줄여 적는다.

    하한이나 상한이 음수면 "--" 구분자가 음부호와 섞여
    "[-0.079--0.253]" 처럼 읽히므로 쉼표로 가른다.
    """
    sep = ", " if (lo < 0 or hi < 0) else "--"
    return "[%s%s%s]" % (f3(lo), sep, f3(hi))


def pm(m, s):
    return "%s $\\pm$ %s" % (f4(m), f4(s))


def tex(s):
    """셀에 들어가는 문자열의 LaTeX 특수문자를 막는다."""
    s = str(s)
    for a, b in [
        ("\\", r"\textbackslash{}"),
        ("&", r"\&"),
        ("%", r"\%"),
        ("$", r"\$"),
        ("#", r"\#"),
        ("_", r"\_"),
        ("{", r"\{"),
        ("}", r"\}"),
        ("~", r"\textasciitilde{}"),
        ("^", r"\textasciicircum{}"),
    ]:
        s = s.replace(a, b)
    return s


